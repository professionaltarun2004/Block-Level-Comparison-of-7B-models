import gc
import json
import random
import statistics
import time
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig, DynamicCache

CHUNK = 1024          # prefill chunk size (must stay below Mistral's 4,096 window)
DECODE_STEPS = 32     # decode steps timed per E2 context length
DEPTHS = [0.1, 0.3, 0.5, 0.7, 0.9]
TRIALS_PER_DEPTH = 2  # E3 trials per (length, depth); 2 -> 10 trials per length

# Standard passkey-retrieval prompt (Mohtashami & Jaggi, 2023, "Landmark Attention").
INTRO = ("There is an important info hidden inside a lot of irrelevant text. "
         "Find it and memorize it. I will quiz you about the important information there.\n\n")
FILLER = "The grass is green. The sky is blue. The sun is yellow. Here we go. There and back again. "
NEEDLE = "The pass key is {key}. Remember it. {key} is the pass key. "
QUESTION = "\n\nWhat is the pass key? The pass key is"


def _dev(model):
    return next(model.parameters()).device


def _sync(dev):
    if dev.type == "cuda":
        torch.cuda.synchronize()


def _mem(dev, peak=False):
    if dev.type != "cuda":
        return 0
    return torch.cuda.max_memory_allocated() if peak else torch.cuda.memory_allocated()


def _free():
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


def load_model(repo, quantize=True):
    tok = AutoTokenizer.from_pretrained(repo)
    kw = dict(dtype=torch.float16, device_map={"": 0}, attn_implementation="sdpa")
    if quantize:
        kw["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True, bnb_4bit_quant_type="nf4", bnb_4bit_compute_dtype=torch.float16)
    model = AutoModelForCausalLM.from_pretrained(repo, **kw).eval()
    return tok, model


def cache_stats(cache):
    """Bytes actually held by the KV cache tensors, and the max number of token positions held."""
    total, held = 0, 0
    for layer in cache.layers:
        for t in (layer.keys, layer.values):
            if isinstance(t, torch.Tensor):
                total += t.numel() * t.element_size()
        if isinstance(layer.keys, torch.Tensor):
            held = max(held, layer.keys.shape[-2])
    return total, held


@torch.no_grad()
def prefill(model, ids, chunk=CHUNK):
    cache, logits = DynamicCache(config=model.config), None
    for s in range(0, ids.shape[1], chunk):
        out = model(input_ids=ids[:, s:s + chunk], past_key_values=cache, use_cache=True, logits_to_keep=1)
        cache, logits = out.past_key_values, out.logits[:, -1].float()
    return cache, logits


@torch.no_grad()
def greedy(model, cache, logits, steps, stop_ids=()):
    dev, toks, times = _dev(model), [], []
    nxt = logits.argmax(-1, keepdim=True)
    for i in range(steps):
        toks.append(int(nxt.item()))
        if toks[-1] in stop_ids or i == steps - 1:
            break
        _sync(dev)
        t0 = time.perf_counter()
        out = model(input_ids=nxt, past_key_values=cache, use_cache=True, logits_to_keep=1)
        _sync(dev)
        times.append(time.perf_counter() - t0)
        cache = out.past_key_values
        nxt = out.logits[:, -1].argmax(-1, keepdim=True)
    return toks, times


def load_done(path):
    done = set()
    p = Path(path)
    if p.exists():
        for line in p.read_text().splitlines():
            if line.strip():
                done.add(json.loads(line)["key"])
    return done


def append(path, row):
    with open(path, "a") as f:
        f.write(json.dumps(row) + "\n")
    print({k: v for k, v in row.items() if k not in ("output",)})


def sanity_check(name, tok, model, out_path, done):
    key = f"sanity|{name}"
    if key in done:
        return
    dev = _dev(model)
    ids = tok("The capital of France is", return_tensors="pt").input_ids.to(dev)
    cache, logits = prefill(model, ids)
    toks, _ = greedy(model, cache, logits, 8)
    append(out_path, dict(key=key, exp="sanity", model=name, finite=bool(torch.isfinite(logits).all()),
                          output=tok.decode(toks)))


def run_e2(name, tok, model, contexts, out_path, done, seed=0):
    """E2/E4: KV-cache bytes, device memory, prefill time and decode latency versus context length."""
    dev = _dev(model)
    g = torch.Generator().manual_seed(seed)
    lo, hi = 300, tok.vocab_size  # regular (non-special) token ids
    _free()
    w_cache, w_logits = prefill(model, torch.randint(lo, hi, (1, 256), generator=g).to(dev))  # warm-up
    greedy(model, w_cache, w_logits, 4)
    del w_cache, w_logits
    _free()
    base = _mem(dev)
    for T in contexts:
        key = f"e2|{name}|{T}"
        if key in done:
            continue
        _free()
        if dev.type == "cuda":
            torch.cuda.reset_peak_memory_stats()
        ids = torch.randint(lo, hi, (1, T), generator=g).to(dev)
        row, oom = dict(key=key, exp="e2", model=name, ctx=T), False
        try:
            _sync(dev)
            t0 = time.perf_counter()
            cache, logits = prefill(model, ids)
            _sync(dev)
            prefill_s = time.perf_counter() - t0
            kv_bytes, held = cache_stats(cache)
            after = _mem(dev) - base
            toks, times = greedy(model, cache, logits, DECODE_STEPS)
            row.update(status="ok", kv_cache_mib=kv_bytes / 2**20, kv_positions_held=held,
                       alloc_after_prefill_mib=after / 2**20, peak_over_weights_mib=(_mem(dev, True) - base) / 2**20,
                       prefill_s=prefill_s, prefill_tok_per_s=T / prefill_s,
                       decode_ms_per_token=1000 * statistics.median(times) if times else None,
                       logits_finite=bool(torch.isfinite(logits).all()))
            del cache, logits
        except torch.OutOfMemoryError:
            oom = True
        if oom:
            _free()
            row.update(status="oom")
        del ids
        _free()
        append(out_path, row)
        if oom:
            break  # longer contexts will not fit either


def passkey_prompt(tok, T, depth, key):
    """Build a passkey prompt of at most T tokens (this model's tokenizer) with the needle at `depth`."""
    def n_tokens(s):
        return len(tok(s).input_ids)
    per = (n_tokens(FILLER * 40) - n_tokens(FILLER * 20)) / 20
    fixed = n_tokens(INTRO + NEEDLE.format(key=key) + QUESTION)
    n = max(1, int((T - fixed) / per))
    while True:
        k = int(round(depth * n))
        text = INTRO + FILLER * k + NEEDLE.format(key=key) + FILLER * (n - k) + QUESTION
        ids = tok(text, return_tensors="pt").input_ids
        if ids.shape[1] <= T or n <= 1:
            return ids, k / n
        n -= max(1, int((ids.shape[1] - T) / per))


def run_e3(name, tok, model, contexts, out_path, done):
    """E3: passkey retrieval accuracy versus context length and needle depth."""
    dev = _dev(model)
    stop = {i for i in (tok.eos_token_id,) if i is not None}
    for T in contexts:
        for depth in DEPTHS:
            for trial in range(TRIALS_PER_DEPTH):
                key = f"e3|{name}|{T}|{depth}|{trial}"
                if key in done:
                    continue
                pk = random.Random(f"{T}-{depth}-{trial}").randint(10000, 99999)  # same keys for every model
                ids, real_depth = passkey_prompt(tok, T, depth, pk)
                row, oom = dict(key=key, exp="e3", model=name, ctx=T, ctx_actual=int(ids.shape[1]),
                                depth=depth, depth_actual=real_depth, trial=trial, passkey=pk), False
                try:
                    t0 = time.perf_counter()
                    cache, logits = prefill(model, ids.to(dev))
                    toks, _ = greedy(model, cache, logits, 12, stop)
                    text = tok.decode(toks)
                    digits = "".join(ch if ch.isdigit() else " " for ch in text).split()
                    row.update(status="ok", output=text, correct=bool(digits) and digits[0] == str(pk),
                               seconds=time.perf_counter() - t0)
                    del cache, logits
                except torch.OutOfMemoryError:
                    oom = True
                if oom:
                    _free()
                    row.update(status="oom", correct=False)
                _free()
                append(out_path, row)


