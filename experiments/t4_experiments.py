import platform  # noqa: E402
import shutil  # noqa: E402
import tempfile  # noqa: E402

MODELS = {
    "mistral-7b": dict(repo="mistralai/Mistral-7B-v0.1", e2=[1024, 2048, 4096, 8192, 16384, 32768, 65536],
                       e3=[4096, 8192, 16384, 32768]),
    "qwen2.5-7b": dict(repo="Qwen/Qwen2.5-7B", e2=[1024, 2048, 4096, 8192, 16384, 32768, 65536],
                       e3=[4096, 8192, 16384, 32768]),
    "llama-7b": dict(repo="huggyllama/llama-7b", e2=[1024, 2048, 4096, 8192, 16384, 32768],
                     e3=[1024, 2048, 4096]),
}
OUT = Path(os.environ.get("T4EXP_OUT", "/content/drive/MyDrive/arxiv_7b_experiments/results.jsonl"))


def read_rows():
    return [json.loads(l) for l in OUT.read_text().splitlines() if l.strip()] if OUT.exists() else []


def plan(name, cfg, rows):
    keys = {r["key"] for r in rows}
    ooms = [r["ctx"] for r in rows if r.get("exp") == "e2" and r.get("model") == name and r.get("status") == "oom"]
    e2 = [T for T in cfg["e2"] if (not ooms or T < min(ooms)) and f"e2|{name}|{T}" not in keys]
    e3 = [T for T in cfg["e3"]
          if any(f"e3|{name}|{T}|{d}|{t}" not in keys for d in DEPTHS for t in range(TRIALS_PER_DEPTH))]
    return (f"sanity|{name}" not in keys), e2, e3


def preflight():
    """Seconds-long check that 4-bit loading and the prefill/decode loop work on this GPU, before any download."""
    from transformers import MistralConfig, MistralForCausalLM
    d = tempfile.mkdtemp()
    MistralForCausalLM(MistralConfig(vocab_size=1000, hidden_size=256, intermediate_size=512, num_hidden_layers=2,
                                     num_attention_heads=4, num_key_value_heads=1, sliding_window=64)).save_pretrained(d)
    q = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4", bnb_4bit_compute_dtype=torch.float16)
    m = AutoModelForCausalLM.from_pretrained(d, dtype=torch.float16, device_map={"": 0}, attn_implementation="sdpa",
                                             quantization_config=q).eval()
    assert any(type(x).__name__ == "Linear4bit" for x in m.modules()), "4-bit quantization was not applied"
    cache, logits = prefill(m, torch.randint(0, 1000, (1, 300), device="cuda"), chunk=128)
    greedy(m, cache, logits, 4)
    assert cache_stats(cache)[1] == 63, "sliding-window cache check failed"
    del m, cache, logits
    _free()
    shutil.rmtree(d, ignore_errors=True)
    print("Preflight OK: 4-bit loading, chunked prefill, decode and sliding-window cache all work on this GPU.", flush=True)


def check_quantized(model):
    n4 = sum(type(x).__name__ == "Linear4bit" for x in model.modules())
    gib = torch.cuda.memory_allocated() / 2**30
    if n4 == 0 or gib > 8:
        raise SystemExit(f"Model is not 4-bit quantized (Linear4bit layers={n4}, weights={gib:.1f} GiB). Stopping.")
    return n4, gib


def gpu_ok():
    return torch.cuda.is_available()


def gpu_info():
    return dict(gpu=torch.cuda.get_device_name(0),
                gpu_mem_gib=round(torch.cuda.get_device_properties(0).total_memory / 2**30, 2))


def main():
    if not gpu_ok():
        sys.exit("No GPU found. Runtime -> Change runtime type -> T4 GPU, then run again.")
    if not OUT.parent.parent.exists():
        sys.exit("Google Drive is not mounted. Run: from google.colab import drive; drive.mount('/content/drive')")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    import accelerate
    import bitsandbytes
    import transformers
    meta = dict(key=f"meta|{time.strftime('%Y-%m-%dT%H:%M:%S')}", exp="meta", **gpu_info(),
                torch=torch.__version__, cuda=torch.version.cuda, transformers=transformers.__version__,
                bitsandbytes=bitsandbytes.__version__, accelerate=accelerate.__version__,
                python=platform.python_version())
    append(OUT, meta)
    preflight()
    for name, cfg in MODELS.items():
        need_sanity, e2_todo, e3_todo = plan(name, cfg, read_rows())
        if not (need_sanity or e2_todo or e3_todo):
            print(f"== {name}: already complete, skipping", flush=True)
            continue
        t0 = time.time()
        print(f"== {name}: loading {cfg['repo']} (uses the download cache if present)", flush=True)
        tok, model = load_model(cfg["repo"])
        n4, gib = check_quantized(model)
        print(f"   loaded in {time.time() - t0:.0f}s; {n4} Linear4bit layers; weights use {gib:.2f} GiB", flush=True)
        done = load_done(OUT)
        sanity_check(name, tok, model, OUT, done)
        run_e2(name, tok, model, e2_todo, OUT, done)
        run_e3(name, tok, model, e3_todo, OUT, done)
        del model
        _free()
        from huggingface_hub import constants
        shutil.rmtree(Path(constants.HF_HUB_CACHE) / ("models--" + cfg["repo"].replace("/", "--")), ignore_errors=True)
        print(f"== {name}: done in {(time.time() - t0) / 60:.1f} min", flush=True)
    rows = read_rows()
    print("\nALL MODELS DONE.", sum(r.get("exp") in ("e2", "e3", "sanity") for r in rows), "result rows in", OUT)


if __name__ == "__main__":
    main()
